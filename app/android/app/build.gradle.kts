// Release signing: android/key.properties (never committed) points at the
// upload key kept outside the repo, in ~/.config/plantai/. Without it, as in
// CI, the release build falls back to the debug key.
val keystoreProperties =
    Properties().apply {
        val file = rootProject.file("key.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }
val hasReleaseKey = !keystoreProperties.isEmpty

// The Flutter tool passes each --dart-define to Gradle base64-encoded.
val dartDefines: Map<String, String> =
    (project.findProperty("dart-defines") as String?)
        .orEmpty()
        .split(",")
        .filter { it.isNotBlank() }
        .map { String(Base64.getDecoder().decode(it)) }
        .associate { it.substringBefore("=") to it.substringAfter("=") }

// Plain HTTP is allowed only to the development hosts: the phone itself
// (`adb reverse`), the emulator's host and, when API_BASE_URL points at the
// local network (10/8, 172.16/12, 192.168/16), that address. Everything else
// needs TLS. This goes away in phase 2, when the API is served over HTTPS.
val privateIpv4 =
    Regex("""^(10\.\d+|172\.(1[6-9]|2\d|3[01])|192\.168)\.\d+\.\d+$""")
val apiHost: String? =
    dartDefines["API_BASE_URL"]?.let { runCatching { URI(it).host }.getOrNull() }
val devCleartextHosts =
    listOf("localhost", "127.0.0.1", "10.0.2.2") +
        listOfNotNull(apiHost?.takeIf { privateIpv4.matches(it) })

abstract class NetworkSecurityConfigTask : DefaultTask() {
    @get:Input
    abstract val cleartextHosts: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val domains =
            cleartextHosts.get().distinct().joinToString("\n") {
                "        <domain includeSubdomains=\"false\">$it</domain>"
            }
        val file = outputDir.file("xml/network_security_config.xml").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by app/android/app/build.gradle.kts; do not edit. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |
            """.trimMargin(),
        )
    }
}

val generateNetworkSecurityConfig =
    tasks.register<NetworkSecurityConfigTask>("generateNetworkSecurityConfig") {
        cleartextHosts.set(devCleartextHosts)
    }

androidComponents {
    onVariants { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(
            generateNetworkSecurityConfig,
            NetworkSecurityConfigTask::outputDir,
        )
    }
}

